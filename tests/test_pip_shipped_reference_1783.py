def _install_pip_shape(directory: Path) -> None:
    """Copy the real `_shipped_reference.py` beside a bare directory --
    the pip route's actual layout: `.supertool.json` absent, the generated
    module present, both beside the same `_supertool.py`."""
    import shutil
    shutil.copy2(REPO_ROOT / "_shipped_reference.py",
                 directory / "_shipped_reference.py")


def test_shipped_config_falls_back_to_the_module_when_the_json_is_absent(
        tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    """The pip-route shape: no `.supertool.json` beside the running module,
    but `_shipped_reference.py` sitting right there instead."""
    _install_pip_shape(tmp_path)
    monkeypatch.setattr(supertool, "_SHIPPED_CONFIG", None)
    monkeypatch.setattr(supertool, "_SHIPPED_CONFIG_STATE", None)
    monkeypatch.setattr(supertool, "_SHIPPED_CONFIG_DIR", str(tmp_path))

    config = supertool._shipped_config()
    assert config.get("builtin-ops"), (
        "no .supertool.json in this directory, and _shipped_reference.py "
        "should have been used as the fallback, but builtin-ops is empty"
    )
    assert supertool._SHIPPED_CONFIG_STATE == "read", (
        f"expected the fallback to count as a real read, got "
        f"{supertool._SHIPPED_CONFIG_STATE!r}"
    )


def test_shipped_config_reports_unreadable_when_the_fallback_module_is_broken(
        tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    """A `_shipped_reference.py` that exists but fails to load -- unreadable
    permissions, or a syntax error in a hand-damaged install -- must not
    silently collapse back to `absent`. #1783 review (Explore/oss:auditor):
    the fallback's `except (OSError, ImportError, SyntaxError, ValueError):
    pass` left `_SHIPPED_CONFIG_STATE` unchanged at `absent` for a reference
    that is present but broken, reintroducing the exact defect item 2 of
    this same issue closed for `.supertool.json` -- one file over."""
    (tmp_path / "_shipped_reference.py").write_text(
        "this is not valid python syntax :::", encoding="utf-8")
    monkeypatch.setattr(supertool, "_SHIPPED_CONFIG", None)
    monkeypatch.setattr(supertool, "_SHIPPED_CONFIG_STATE", None)
    monkeypatch.setattr(supertool, "_SHIPPED_CONFIG_DIR", str(tmp_path))

    config = supertool._shipped_config()
    assert config == {} or not config.get("builtin-ops")
    assert supertool._SHIPPED_CONFIG_STATE == "unreadable", (
        f"a present-but-broken fallback module was reported as "
        f"{supertool._SHIPPED_CONFIG_STATE!r}, indistinguishable from a "
        f"genuinely absent install"
    )


def test_shipped_config_stays_absent_with_neither_file_nor_module(
        tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    """The genuinely broken install: neither `.supertool.json` nor
    `_shipped_reference.py` beside the running module. Must not silently
    find this repo's own `_shipped_reference.py` via `sys.path` instead."""
    monkeypatch.setattr(supertool, "_SHIPPED_CONFIG", None)
    monkeypatch.setattr(supertool, "_SHIPPED_CONFIG_STATE", None)
    monkeypatch.setattr(supertool, "_SHIPPED_CONFIG_DIR", str(tmp_path))

    config = supertool._shipped_config()
    assert config == {} or not config.get("builtin-ops")
    assert supertool._SHIPPED_CONFIG_STATE == "absent"


def test_help_for_a_builtin_op_works_on_the_pip_shape(
        tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    """End to end: `help:read` must not print the "incomplete install"
    sentence when the only thing missing is `.supertool.json` itself."""
    _install_pip_shape(tmp_path)
    monkeypatch.setattr(supertool, "_SHIPPED_CONFIG", None)
    monkeypatch.setattr(supertool, "_SHIPPED_CONFIG_STATE", None)
    monkeypatch.setattr(supertool, "_SHIPPED_CONFIG_DIR", str(tmp_path))
    monkeypatch.setattr(supertool, "_CONFIG", {})
    monkeypatch.setattr(supertool, "_CONFIG_CHECKED", True)
    monkeypatch.setattr(supertool, "_CONFIG_PATH", "/somewhere/else/.supertool.json")

    out = supertool.op_help("read")
    assert "incomplete install" not in out, out
    assert "not there" not in out, out
    assert "read:PATH" in out or "syntax" in out.lower(), out


