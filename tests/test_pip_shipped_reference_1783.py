"""#1783 items 1-3: the pip route, the exists/open race one directory up,
and the else arm that asserts a specific claim about an unreached verdict.

Item 1 -- the pip route ships neither `.supertool.json` nor `presets/`
(`py-modules = ["supertool", "_supertool"]`, no packages, no `MANIFEST.in`),
so `_shipped_config()` found nothing and every `help:OP` for an
undocumented-by-project op printed a false "incomplete install" sentence about
a route the README endorses. Every declarative packaging route that could
carry a data file there was tried and rejected in the issue's own comment
thread -- `package-data`, `MANIFEST.in` + `include-package-data`,
`data-files` -- so the fix ships `_shipped_reference.py`, an importable
module carrying only the `builtin-ops` block, generated by
`.github/scripts/generate_shipped_reference.py`. This test builds the real
wheel and lists its contents -- the issue's own instruction, not a re-read of
the manifest.

Item 2 -- `_shipped_config()` used `os.path.exists(path)` as a pre-check
before `open()`. #1781 fixed the file-level case (`chmod 000` on the file
itself); the same defect survives one directory up, where an unreadable
*directory* makes `os.path.exists` swallow `EACCES` and return `False`, so a
reference that is present and readable reports as "not there" -- the exact
false sentence #1781 was filed to remove, one level up. The fix drops the
`exists()` pre-check, opens unconditionally, and branches on
`FileNotFoundError` (genuinely absent) versus any other `OSError`
(unreadable).

Item 3 -- the final `else` arm in the "no documented help" refusal caught
every verdict that was not `"unreadable"` or `"absent"`, including `"read"`
and any future fourth value, and asserted "was read and does not document it
either" even for a value nobody has produced. The fix makes `"read"` an
explicit `elif` and gives the real `else` an honest "verdict unknown"
sentence.
"""
from __future__ import annotations

import json
import os
import subprocess
import sys
import venv
import zipfile
from pathlib import Path

import pytest

import supertool

REPO_ROOT = Path(__file__).parent.parent


# ---------------------------------------------------------------------------
# Item 1 -- the pip route
# ---------------------------------------------------------------------------


@pytest.mark.slow
def test_the_built_wheel_ships_a_shipped_reference_module(tmp_path: Path) -> None:
    """Build the actual wheel and list it -- the issue's own instruction.

    Before the fix this wheel contained exactly `_supertool.py`, `supertool.py`
    and the dist-info directory. The fix must add `_shipped_reference.py`
    without removing or renaming either of the other two.
    """
    venv_dir = tmp_path / "buildenv"
    venv.EnvBuilder(with_pip=True).create(venv_dir)
    bin_dir = venv_dir / ("Scripts" if sys.platform == "win32" else "bin")
    venv_python = bin_dir / ("python.exe" if sys.platform == "win32" else "python")

    subprocess.run(
        [str(venv_python), "-m", "pip", "install", "build"],
        check=True, capture_output=True, encoding="utf-8", errors="replace",
    )

    out_dir = tmp_path / "dist"
    build = subprocess.run(
        [str(venv_python), "-m", "build", "--wheel", "--outdir", str(out_dir),
         str(REPO_ROOT)],
        capture_output=True, encoding="utf-8", errors="replace",
    )
    assert build.returncode == 0, (
        "wheel build failed\nstdout: " + build.stdout + "\nstderr: " + build.stderr
    )

    wheels = list(out_dir.glob("*.whl"))
    assert len(wheels) == 1, f"expected exactly one wheel, found {wheels}"

    with zipfile.ZipFile(wheels[0]) as zf:
        names = {Path(n).name for n in zf.namelist()}

    assert "_shipped_reference.py" in names, (
        f"the wheel does not ship _shipped_reference.py -- pip installs "
        f"still carry no builtin-ops reference (#1783). Wheel contents: "
        f"{sorted(names)}"
    )
    assert "_supertool.py" in names and "supertool.py" in names, (
        f"the fix must not drop either existing module: {sorted(names)}"
    )


def test_generated_reference_is_not_stale() -> None:
    """The generator's output and the checked-in file must agree.

    A `.supertool.json` edited without re-running the generator is exactly
    the drift this guards: pip installs would keep documenting a `builtin-ops`
    block this repo no longer has.
    """
    import importlib.util

    spec = importlib.util.spec_from_file_location(
        "_generate_shipped_reference_1783",
        REPO_ROOT / ".github" / "scripts" / "generate_shipped_reference.py")
    gen = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(gen)

    expected = gen.render()
    actual = (REPO_ROOT / "_shipped_reference.py").read_text(encoding="utf-8")
    assert actual == expected, (
        "_shipped_reference.py is stale -- run "
        "`python3 .github/scripts/generate_shipped_reference.py` and commit "
        "the result."
    )


def test_generator_writes_with_explicit_lf_newline(tmp_path: Path,
                                                     monkeypatch: pytest.MonkeyPatch) -> None:
    """`main()`'s `open(out_path, "w", encoding="utf-8")` has no `newline=`,
    so on a Windows contributor's machine text-mode write translates every
    newline in the rendered string to `os.linesep` (CRLF) -- invisible on
    macOS/Linux where `os.linesep` already is a bare newline, and not caught
    by `test_generated_reference_is_not_stale` either: that test reads the
    written file back with `Path.read_text()`, which applies universal-
    newline translation and silently converts the CRLF back before the
    comparison, so the test passes even though the bytes just written to
    disk differ from what a non-Windows run produces from the same source
    data (#1783 review, oss:auditor). #1783's own comment thread already
    established this repo has no `.gitattributes` pinning this file to LF."""
    import importlib.util
    import unittest.mock

    spec = importlib.util.spec_from_file_location(
        "_generate_shipped_reference_1783_newline",
        REPO_ROOT / ".github" / "scripts" / "generate_shipped_reference.py")
    gen = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(gen)

    monkeypatch.setattr(gen, "REPO_ROOT", str(REPO_ROOT))
    real_open = open
    captured = {}

    def spy_open(path, *args, **kwargs):
        if str(path) == os.path.join(str(REPO_ROOT), "_shipped_reference.py"):
            captured["newline"] = kwargs.get("newline", "sentinel-not-passed")
            return real_open(os.devnull, "w", encoding="utf-8")
        return real_open(path, *args, **kwargs)

    with unittest.mock.patch("builtins.open", side_effect=spy_open):
        gen.main()

    assert captured, "main() never opened _shipped_reference.py for writing"
    assert captured["newline"] == "\n", (
        f"main() wrote _shipped_reference.py without pinning newline to a "
        f"bare newline (got {captured['newline']!r}) -- on Windows this "
        f"writes CRLF via the platform default os.linesep, a line-ending-"
        f"only diff on a file meant to be byte-reproducible across the "
        f"whole matrix"
    )


def test_generated_reference_carries_builtin_ops_only_not_the_whole_file() -> None:
    """The `ops` section (preset config overrides) must never be folded in --
    it documents presets/ the pip route does not ship (#1783's own comment)."""
    import _shipped_reference

    with open(REPO_ROOT / ".supertool.json", encoding="utf-8") as fh:
        project_config = json.load(fh)

    assert _shipped_reference.BUILTIN_OPS == project_config["builtin-ops"]
    assert not hasattr(_shipped_reference, "OPS")
    source = (REPO_ROOT / "_shipped_reference.py").read_text(encoding="utf-8")
    # None of the eight preset-override op names should appear as a JSON key
    # -- they only exist in `.supertool.json`'s `ops` section.
    for op_name in project_config.get("ops", {}):
        assert f'"{op_name}":' not in source, (
            f"{op_name!r} is a preset-config override from the `ops` "
            f"section and should not be in the generated builtin-ops module"
        )


