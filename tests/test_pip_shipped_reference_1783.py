@pytest.fixture
def consumer_tree(monkeypatch: pytest.MonkeyPatch):
    monkeypatch.setattr(supertool, "_CONFIG", {})
    monkeypatch.setattr(supertool, "_CONFIG_CHECKED", True)
    monkeypatch.setattr(supertool, "_CONFIG_PATH", "/somewhere/else/.supertool.json")


def _install(directory: Path, monkeypatch: pytest.MonkeyPatch, contents):
    monkeypatch.setattr(supertool, "_SHIPPED_CONFIG", None)
    monkeypatch.setattr(supertool, "_SHIPPED_CONFIG_STATE", None)
    monkeypatch.setattr(supertool, "_SHIPPED_CONFIG_DIR", str(directory))
    path = directory / ".supertool.json"
    if contents is not None:
        path.write_text(contents, encoding="utf-8")
    return path


def test_an_unreadable_install_directory_is_not_reported_as_absent(
        tmp_path: Path, monkeypatch: pytest.MonkeyPatch, consumer_tree) -> None:
    """The actual bug: `chmod 000` on the *directory*, with a real, readable
    reference file inside it. `os.path.exists` swallows the resulting
    `EACCES` and returns False, so this used to render byte-identical to a
    genuinely absent install."""
    outer = tmp_path / "outer"
    outer.mkdir()
    inner = outer / "install"
    inner.mkdir()
    _install(inner, monkeypatch,
              json.dumps({"builtin-ops": {"read": {"syntax": "read:PATH"}}}))

    inner.chmod(0o000)
    try:
        try:
            os.listdir(str(inner))
        except OSError:
            pass
        else:
            pytest.skip("this process ignores directory mode bits (root, or "
                        "a platform that does not enforce them); the state "
                        "cannot be built here")
        out = supertool.op_help("read")
    finally:
        inner.chmod(0o755)

    assert "not there" not in out and "absent" not in out.lower(), (
        f"an unreadable directory containing a real reference was reported "
        f"as absent, the exact defect #1781 fixed one level down: {out!r}"
    )
    assert "UNKNOWN" in out, out


# The five shapes the issue names, run together as positive controls proving
# the fix above did not just move the bug -- absent, unreadable file, scalar
# JSON, a good config, and the unreadable-directory case above.


def test_shape_absent(tmp_path: Path, monkeypatch: pytest.MonkeyPatch,
                       consumer_tree) -> None:
    _install(tmp_path, monkeypatch, None)
    out = supertool.op_help("read")
    assert "not there" in out or "absent" in out
    assert "UNKNOWN" not in out


def test_shape_unreadable_file(tmp_path: Path, monkeypatch: pytest.MonkeyPatch,
                                consumer_tree) -> None:
    path = _install(tmp_path, monkeypatch,
                    json.dumps({"builtin-ops": {"read": {"syntax": "read:PATH"}}}))
    path.chmod(0o000)
    try:
        try:
            path.read_text(encoding="utf-8")
        except OSError:
            pass
        else:
            pytest.skip("this process can read a 0o000 file; the state "
                        "cannot be built here")
        out = supertool.op_help("read")
    finally:
        path.chmod(0o644)
    assert "UNKNOWN" in out
    assert "not there" not in out


def test_shape_scalar_json(tmp_path: Path, monkeypatch: pytest.MonkeyPatch,
                            consumer_tree) -> None:
    _install(tmp_path, monkeypatch, json.dumps(["a list, not an object"]))
    out = supertool.op_help("read")
    assert "UNKNOWN" in out


def test_shape_good_config(tmp_path: Path, monkeypatch: pytest.MonkeyPatch,
                            consumer_tree) -> None:
    _install(tmp_path, monkeypatch,
              json.dumps({"builtin-ops": {"read": {"syntax": "read:PATH"}}}))
    out = supertool.op_help("read")
    assert "read:PATH" in out


