def test_an_unexpected_verdict_is_reported_as_unknown_not_as_read(
        tmp_path: Path, monkeypatch: pytest.MonkeyPatch, consumer_tree) -> None:
    """Construct the unreached fourth state directly, as the issue's own
    reproduction did: nothing in the tree ever sets `_SHIPPED_CONFIG_STATE`
    to anything but `read` / `absent` / `unreadable`, so this state can only
    be built by hand."""
    monkeypatch.setattr(supertool, "_SHIPPED_CONFIG", {})
    monkeypatch.setattr(supertool, "_SHIPPED_CONFIG_STATE", "some-future-state")
    monkeypatch.setattr(supertool, "_SHIPPED_CONFIG_DIR", str(tmp_path))

    out = supertool.op_help("read")
    assert "was read and does not document" not in out, (
        f"an unrecognised verdict was asserted as though it were the "
        f"definite 'read' case: {out!r}"
    )
    assert "unknown" in out.lower(), out


def test_the_read_verdict_still_says_the_true_thing(
        tmp_path: Path, monkeypatch: pytest.MonkeyPatch, consumer_tree) -> None:
    """The positive control for item 3: the real `read` case must keep
    saying its true sentence once it becomes an explicit `elif`."""
    _install(tmp_path, monkeypatch, json.dumps({"builtin-ops": {}}))
    out = supertool.op_help("read")
    assert "was read and does not document" in out
    assert "unknown" not in out.lower()
